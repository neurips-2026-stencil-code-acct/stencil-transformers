[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$ArtifactRoot = Split-Path -Parent $PSScriptRoot
$ParentVenvPython = Join-Path (Split-Path -Parent $ArtifactRoot) '.venv\Scripts\python.exe'
$LocalVenvPython = Join-Path $ArtifactRoot '.venv\Scripts\python.exe'

if (Test-Path -LiteralPath $ParentVenvPython) {
    $Python = $ParentVenvPython
} elseif (Test-Path -LiteralPath $LocalVenvPython) {
    $Python = $LocalVenvPython
} else {
    $Python = (Get-Command python -ErrorAction Stop).Source
}

$Commands = @(
    [pscustomobject]@{ Script = 'analysis\robustness_checks\test_robustness_checks.py'; Arguments = @() },
    [pscustomobject]@{ Script = 'analysis\robustness_checks\bootstrap_model_effects.py'; Arguments = @('--pdes', 'heat,lf') },
    [pscustomobject]@{ Script = 'analysis\robustness_checks\j_minus_identity_circulance.py'; Arguments = @('--pdes', 'heat,lf') }
)

Push-Location $ArtifactRoot
try {
    foreach ($Command in $Commands) {
        Write-Host "[derive] $($Command.Script) $($Command.Arguments -join ' ')"
        & $Python -B $Command.Script @($Command.Arguments)
        if ($LASTEXITCODE -ne 0) {
            throw "Derived-result command failed with exit code $LASTEXITCODE"
        }
    }
} finally {
    Pop-Location
}

Write-Host 'Derived heat/Lax--Friedrichs summaries rebuilt successfully.'
Write-Host 'Run build_manifest.py if you intend to keep regenerated byte-level outputs.'
